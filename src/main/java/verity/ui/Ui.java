package verity.ui;

import java.time.LocalDate;
import java.util.List;
import java.util.Scanner;

import verity.task.Task;
import verity.task.TaskList;

/**
 * Handles all interactions with the user.
 */
public class Ui {
    private static final String HORIZONTAL_LINE =
            "____________________________________________________________\n";

    private final Scanner scanner;

    /**
     * Creates a UI that reads from standard input.
     */
    public Ui() {
        this.scanner = new Scanner(System.in);
    }

    /**
     * Reads the next verity.command entered by the user.
     *
     * @return User verity.command.
     */
    public String readCommand() {
        return scanner.nextLine();
    }

    /**
     * Displays the startup greeting.
     */
    public void showGreeting() {
        // This ASCII art for VERITY was generated by Codex Luna High.
        String banner =
                "V   V  EEEEE  RRRR   IIIII  TTTTT  Y   Y\n"
                        + "V   V  E      R   R    I      T     Y Y\n"
                        + " V V   EEEE   RRRR     I      T      Y\n"
                        + "  V    E      R R      I      T      Y\n"
                        + "  V    EEEEE  R  RR  IIIII    T      Y";

        System.out.println(HORIZONTAL_LINE
                + banner + "\n\n"
                + "Hello! I'm Verity.\n"
                + "I speak only the truth.\n"
                + "What can I do for you?\n"
                + HORIZONTAL_LINE);
    }

    /**
     * Displays the exit message.
     */
    public void showExit() {
        System.out.println(HORIZONTAL_LINE
                + "    Bye. Hope to see you again soon!\n"
                + HORIZONTAL_LINE);
    }

    /**
     * Displays a task that has been added.
     *
     * @param task Added task.
     * @param taskCount Number of tasks after the addition.
     */
    public void showTaskAdded(Task task, int taskCount) {
        System.out.println(HORIZONTAL_LINE
                + "     Got it. I've added this task:\n"
                + "       " + task.getStatus() + "\n"
                + "     Now you have " + taskCount
                + " tasks in the list.\n"
                + HORIZONTAL_LINE);
    }

    /**
     * Displays a task that has been marked as completed.
     *
     * @param task Updated task.
     */
    public void showTaskMarked(Task task) {
        System.out.println(HORIZONTAL_LINE);
        System.out.println(
                "Nice! I've marked this task as done:\n");
        System.out.println(
                task.getStatus() + "\n" + HORIZONTAL_LINE);
    }

    /**
     * Displays a task that has been marked as incomplete.
     *
     * @param task Updated task.
     */
    public void showTaskUnmarked(Task task) {
        System.out.println(HORIZONTAL_LINE);
        System.out.println(
                "Ok, I've marked this task as not done yet:\n");
        System.out.println(
                task.getStatus() + "\n" + HORIZONTAL_LINE);
    }

    /**
     * Displays a deleted task.
     *
     * @param task Deleted task.
     * @param taskCount Number of tasks after deletion.
     */
    public void showTaskDeleted(Task task, int taskCount) {
        System.out.println(HORIZONTAL_LINE);
        System.out.println("Noted. I've removed this task:\n");
        System.out.println(
                task.getStatus() + "\n" + HORIZONTAL_LINE);
        System.out.println(
                "Now you have " + taskCount
                        + " tasks in the list.\n");
        System.out.println(HORIZONTAL_LINE);
    }

    /**
     * Displays all tasks.
     *
     * @param taskList verity.task.Task list to display.
     */
    public void showTaskList(TaskList taskList) {
        System.out.println(HORIZONTAL_LINE);
        System.out.println(
                "    Here are the tasks in your list:\n");

        for (int i = 0; i < taskList.size(); i++) {
            System.out.println(
                    "    " + (i + 1) + "."
                            + taskList.get(i).getStatus());
        }
        System.out.println(HORIZONTAL_LINE);
    }

    /**
     * Displays tasks occurring on a date.
     *
     * @param date Searched date.
     * @param matchingTasks Tasks occurring on the date.
     */
    public void showTasksOn(
            LocalDate date, List<Task> matchingTasks) {
        System.out.println(HORIZONTAL_LINE);
        System.out.println("    Tasks on " + date + ":\n");

        for (Task task : matchingTasks) {
            System.out.println("    " + task.getStatus());
        }

        if (matchingTasks.isEmpty()) {
            System.out.println(
                    "    There are no tasks on this date.");
        }
        System.out.println(HORIZONTAL_LINE);
    }

    /**
     * Displays tasks whose descriptions match a search keyword.
     *
     * @param matchingTasks Tasks matching the keyword.
     */
    public void showMatchingTasks(List<Task> matchingTasks) {
        System.out.println(HORIZONTAL_LINE);
        System.out.println(
                "    Here are the matching tasks in your list:\n");

        for (int i = 0; i < matchingTasks.size(); i++) {
            System.out.println(
                    "    " + (i + 1) + "."
                            + matchingTasks.get(i).getStatus());
        }

        if (matchingTasks.isEmpty()) {
            System.out.println("    There are no matching tasks.");
        }
        System.out.println(HORIZONTAL_LINE);
    }

    /**
     * Displays an invalid-verity.command or input error.
     *
     * @param message Error message.
     */
    public void showCommandError(String message) {
        System.out.println(HORIZONTAL_LINE
                + "     Speak your truth. " + message + "\n"
                + HORIZONTAL_LINE);
    }

    /**
     * Displays an error encountered while loading the data file.
     */
    public void showLoadingError() {
        System.out.println(HORIZONTAL_LINE
                + "     I could not load your saved tasks.\n"
                + "     Please check the data file and try again.\n"
                + HORIZONTAL_LINE);
    }

    /**
     * Displays an error caused by corrupted saved data.
     *
     * @param message Description of the corrupted data.
     */
    public void showCorruptedDataError(String message) {
        System.out.println(HORIZONTAL_LINE
                + "     The saved task data is corrupted.\n"
                + "     " + message + "\n"
                + HORIZONTAL_LINE);
    }

    /**
     * Displays an error encountered while saving tasks.
     */
    public void showSavingError() {
        System.out.println(HORIZONTAL_LINE
                + "     I could not save your tasks.\n"
                + "     Please check the data folder and try again.\n"
                + HORIZONTAL_LINE);
    }
}
